CODE_RE = re.compile(r"^[A-Z]{2}$")
PKG_RE = re.compile(r"^[a-z][a-z0-9_]*$")


def render(text, code, package, name_zh, country, name_en=None):
    country = country.upper()
    return (text.replace("__CODE__", code)
            .replace("__PKG__", package)
            .replace("__NAME_ZH__", name_zh)
            .replace("__NAME_EN__", name_en or package.replace("_", " ").title())
            .replace("__COMBINED__", report_kit.combined_workbook_name(country, code, "YYYY-MM"))
            .replace("__COUNTRY_ZH__", markets.country_name(country))
            .replace("__COUNTRY__", country)
            .replace("__TODAY__", datetime.date.today().isoformat()))


def check_args(code, package, country, root):
    """Refuse a code, package or country that would clash or is malformed."""
    errors = []
    if not CODE_RE.match(code or ""):
        errors.append("平台代码要两个大写字母（如 AZ），给的是 %r" % code)
    elif code in markets.PLATFORMS:
        errors.append("平台代码 %s 已经被 %s 用了（代码一旦用过就不再改，见 REPORT_FAMILY §1）"
                      % (code, markets.PLATFORMS[code].package))
    if not PKG_RE.match(package or ""):
        errors.append("包名要小写字母、数字、下划线（如 amazon），给的是 %r" % package)
    elif any(p.package == "platforms." + package for p in markets.PLATFORMS.values()):
        errors.append("platforms.%s 已经登记在 core/markets.py" % package)
    if (country or "").upper() not in markets.COUNTRIES:
        errors.append("国家代码 %r 不在 core/markets.py COUNTRIES 里（先在那里加上）" % country)
    if os.path.exists(os.path.join(root, package or "")):
        errors.append("%s 已经存在，不覆盖" % os.path.join(root, package))
    return errors


def registry_line(code, package, name_zh, country, name_en=None):
    name_en = name_en or package.replace("_", " ").title()
    pattern = r"\s*".join(re.escape(w) for w in name_en.lower().split())
    return ('    ("%s", Platform("%s", "platforms.%s", "%s", "%s",\n'
            '                    re.compile(r"%s", re.I), ("%s",))),'
            % (code, code, package, name_zh, name_en, pattern, country.upper()))


def generate(code, package, name_zh, country, root=None, name_en=None):
    """Write platforms/<package>/ under root (default: this repository's
    platforms/). Returns the folder."""
    root = root or os.path.join(ROOT, "platforms")
    errors = check_args(code, package, country, root)
    if errors:
        raise ValueError("；".join(errors))
    folder = os.path.join(root, package)
    os.makedirs(folder)
    for name, text in FILES.items():
        with io.open(os.path.join(folder, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(render(text, code, package, name_zh, country, name_en))
    return folder


def main(argv=None):
    ap = argparse.ArgumentParser(description="scaffold platforms/<package>/ for a new platform")
    ap.add_argument("code", help="two-letter platform code, e.g. AZ (never changes once used)")
    ap.add_argument("package", help="package name under platforms/, e.g. amazon")
    ap.add_argument("name_zh", help="Chinese name shown to operators, e.g. 亚马逊")
    ap.add_argument("country", help="first country, ISO code in core/markets.py, e.g. MX")
    ap.add_argument("--name-en", default=None, help="English name (default: from the package)")
    ap.add_argument("--root", default=None, help="where to create it (default: platforms/)")
    a = ap.parse_args(argv)
    code = a.code.upper()
    try:
        folder = generate(code, a.package, a.name_zh, a.country, a.root, a.name_en)
    except ValueError as e:
        print("[错误] %s" % e)
        return 2
    print("已生成 %s：" % folder)
    for name in sorted(FILES):
        print("  %s" % name)
